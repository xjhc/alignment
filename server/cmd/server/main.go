// debugEventTypesHandler handles debug event types requests
// @Summary Get all event and action types
// @Description Get a comprehensive list of all available event and action types in the system for debugging and contract verification
// @Tags debug
// @Produce json
// @Success 200 {object} EventTypesResponse
// @Failure 405 {object} ErrorResponse "Method not allowed"
// @Router /api/debug/event-types [get]
func (s *Server) debugEventTypesHandler(w http.ResponseWriter, r *http.Request) {
	// Only allow GET requests
	if r.Method != http.MethodGet {
		http.Error(w, "Method not allowed", http.StatusMethodNotAllowed)
		return
	}

	// Convert the core.EventTypeValues to string slice
	eventTypes := make([]string, len(core.EventTypeValues))
	for i, eventType := range core.EventTypeValues {
		eventTypes[i] = string(eventType)
	}

	// Convert the core.ActionTypeValues to string slice
	actionTypes := make([]string, len(core.ActionTypeValues))
	for i, actionType := range core.ActionTypeValues {
		actionTypes[i] = string(actionType)
	}

	response := EventTypesResponse{
		EventTypes:   eventTypes,
		ActionTypes:  actionTypes,
		TotalEvents:  len(eventTypes),
		TotalActions: len(actionTypes),
	}

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(response)
}


func main() {
	// Parse command-line flags
	mcpMode := flag.Bool("mcp", false, "Run in MCP mode (Model Context Protocol)")
	flag.Parse()

	// Create server
	server, err := NewServer()
	if err != nil {
		log.Fatalf("Failed to create server: %v", err)
	}

	if *mcpMode {
		// Run MCP server on stdio
		logger.GetLogger().Info("Starting server in MCP mode")
		server.mcpServer.Run()
		return
	}

	// Standard HTTP/WebSocket server mode
	port := os.Getenv("PORT")
	if port == "" {
		port = "8080"
	}

	// Setup routes
	server.setupRoutes()

	// Start server components
	server.Start()

	// Setup graceful shutdown
	c := make(chan os.Signal, 1)
	signal.Notify(c, os.Interrupt, syscall.SIGTERM)

	go func() {
		<-c
		logger.GetLogger().Info("Received shutdown signal")
		server.Stop()
		os.Exit(0)
	}()

	fmt.Printf("Alignment server starting on port %s\n", port)
	fmt.Println("WebSocket endpoint: /ws")
	fmt.Println("API endpoints:")
	fmt.Println("  GET  /health")
	fmt.Println("  GET  /metrics               - Prometheus metrics")
	fmt.Println("  GET  /api/games               - List lobbies")
	fmt.Println("  POST /api/games              - Create lobby")
	fmt.Println("  POST /api/games/{gameId}/join - Join lobby")
	fmt.Println("  GET  /api/stats")
	fmt.Println("  GET  /api/debug/event-types   - List event and action types")
	fmt.Println("Admin endpoints (requires authentication):")
	fmt.Println("  GET  /admin                  - Admin dashboard UI")
	fmt.Println("  GET  /admin/status           - Server status")
	fmt.Println("  GET  /admin/games            - List active games")
	fmt.Println("  GET  /admin/games/{id}/state - Get game state")
	fmt.Println("  DELETE /admin/games/{id}     - Terminate game")

	logger.GetLogger().Info("Server listening", "port", port)
	if err := http.ListenAndServe(":"+port, nil); err != nil {
		log.Fatal("Server failed to start:", err)
	}
}