// joinLobby handles lobby join requests
// @Summary Join an existing lobby
// @Description Join an existing game lobby as a player
// @Tags lobbies
// @Accept json
// @Produce json
// @Param gameId path string true "Game ID"
// @Param request body JoinLobbyRequest true "Join lobby request"
// @Success 200 {object} JoinLobbyResponse
// @Failure 400 {object} ErrorResponse
// @Failure 404 {object} ErrorResponse "Lobby not found"
// @Failure 409 {object} ErrorResponse "Lobby is full or not accepting players"
// @Failure 500 {object} ErrorResponse
// @Router /api/games/{gameId}/join [post]
func (s *Server) joinLobby(w http.ResponseWriter, r *http.Request, gameID string) {
	log := logger.WithFields(map[string]interface{}{
		"endpoint": "joinLobby",
		"game_id":  gameID,
	})
	var req JoinLobbyRequest

	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		log.Warn("Invalid request body", "error", err)
		http.Error(w, "Invalid request body", http.StatusBadRequest)
		return
	}

	// Validate request parameters to prevent abuse
	if err := s.validateJoinLobbyRequest(req); err != nil {
		log.Warn("Invalid join lobby request", "error", err)
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}

	// Determine the actual user ID (prefer authenticated user over guest)
	actualUserID := req.UserID
	if s.authHandlers != nil {
		if authUserID, err := s.authHandlers.GetAuthenticatedUserID(r); err == nil {
			actualUserID = authUserID
			log.Info("Using authenticated user ID instead of guest ID", "auth_user_id", authUserID, "guest_id", req.UserID)
		}
	}

	log.Info("Player joining lobby", "user_id", actualUserID, "player_name", req.PlayerName, "game_id", gameID)

	// Check single-session rule
	if err := s.activeUserTracker.CheckSingleSession(actualUserID, gameID); err != nil {
		log.Warn("Single-session rule violation", "user_id", actualUserID, "error", err)
		http.Error(w, "You are already in an active game session", http.StatusConflict)
		return
	}

	playerID, sessionToken, err := s.lifecycleManager.JoinLobby(gameID, actualUserID, req.PlayerName, req.PlayerAvatar)
	if err != nil {
		log.Warn("Failed to join lobby", "error", err, "player_name", req.PlayerName)
		switch err.Error() {
		case "lobby not found":
			http.Error(w, "Lobby not found", http.StatusNotFound)
		case "lobby is not accepting new players":
			http.Error(w, "Lobby is not accepting new players", http.StatusConflict)
		case "lobby is full":
			http.Error(w, "Lobby is full", http.StatusConflict)
		default:
			http.Error(w, "Failed to join lobby", http.StatusInternalServerError)
		}
		return
	}

	// Record metrics
	metrics.RecordPlayerJoined()

	// Add user to active session tracker
	if err := s.activeUserTracker.AddUserSession(actualUserID, gameID, playerID); err != nil {
		log.Error("Failed to add user to active session tracker", "error", err, "user_id", actualUserID)
		// Don't fail the request, just log the error
	}

	response := JoinLobbyResponse{
		GameID:       gameID,
		PlayerID:     playerID,
		SessionToken: sessionToken,
	}

	log.Info("Player joined lobby successfully", "player_id", playerID, "player_name", req.PlayerName, "user_id", actualUserID)

	w.Header().Set("Content-Type", "application/json")
	json.NewEncoder(w).Encode(response)
}

