// containsSuspiciousChars checks for characters that might be used maliciously
func containsSuspiciousChars(s string) bool {
	// Check for control characters, excessive whitespace, or script-injection patterns
	for _, r := range s {
		if r < 32 && r != 9 && r != 10 && r != 13 { // Allow tab, newline, carriage return
			return true
		}
		// Check for common script injection patterns
		if r == '<' || r == '>' || r == '\'' || r == '"' || r == '&' {
			return true
		}
	}

	// Check for excessive whitespace
	if len(strings.TrimSpace(s)) == 0 {
		return true
	}

	return false
}

