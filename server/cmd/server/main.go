// createLobby handles lobby creation requests
// @Summary Create a new lobby
// @Description Create a new game lobby with the requesting player as host
// @Tags lobbies
// @Accept json
// @Produce json
// @Param request body CreateLobbyRequest true "Lobby creation request"
// @Success 201 {object} CreateLobbyResponse
// @Failure 400 {object} ErrorResponse
// @Failure 500 {object} ErrorResponse
// @Router /api/games [post]
func (s *Server) createLobby(w http.ResponseWriter, r *http.Request) {
	log := logger.WithField("endpoint", "createLobby")
	var req CreateLobbyRequest

	// Read and decode the request body
	if err := json.NewDecoder(r.Body).Decode(&req); err != nil {
		log.Warn("Invalid request body", "error", err)
		http.Error(w, "Invalid request body", http.StatusBadRequest)
		return
	}

	// Validate request parameters to prevent abuse
	if err := s.validateCreateLobbyRequest(req); err != nil {
		log.Warn("Invalid create lobby request", "error", err)
		http.Error(w, err.Error(), http.StatusBadRequest)
		return
	}

	// Check admission control (using player name as user ID for simplicity)
	requestBody, _ := json.Marshal(req)
	if err := s.admissionController.CheckAdmission(req.PlayerName, requestBody); err != nil {
		if waitlistErr, ok := err.(*admission.WaitlistError); ok {
			admission.WriteWaitlistResponse(w, waitlistErr)
			return
		}
		log.Error("Admission control error", "error", err)
		http.Error(w, "Internal server error", http.StatusInternalServerError)
		return
	}

	if req.LobbyName == "" {
		req.LobbyName = fmt.Sprintf("%s's Game", req.PlayerName)
	}

	if req.UserID == "" {
		log.Warn("User ID is required")
		http.Error(w, "User ID is required", http.StatusBadRequest)
		return
	}

	if req.PlayerName == "" {
		log.Warn("Player name is required")
		http.Error(w, "Player name is required", http.StatusBadRequest)
		return
	}

	// Determine the actual user ID (prefer authenticated user over guest)
	actualUserID := req.UserID
	if s.authHandlers != nil {
		if authUserID, err := s.authHandlers.GetAuthenticatedUserID(r); err == nil {
			actualUserID = authUserID
			log.Info("Using authenticated user ID instead of guest ID", "auth_user_id", authUserID, "guest_id", req.UserID)
		}
	}

	log.Info("Creating lobby", "user_id", actualUserID, "player_name", req.PlayerName, "lobby_name", req.LobbyName, "is_private", req.IsPrivate)

	// Check single-session rule - generate a temporary lobby ID for the check
	tempLobbyID := "CREATING"
	if err := s.activeUserTracker.CheckSingleSession(actualUserID, tempLobbyID); err != nil {
		log.Warn("Single-session rule violation", "user_id", actualUserID, "error", err)
		http.Error(w, "You are already in an active game session", http.StatusConflict)
		return
	}

	// Call the new, centralized method in the GameLifecycleManager
	// This ensures only one hostPlayerID is generated and used consistently
	lobbyID, hostPlayerID, sessionToken, err := s.lifecycleManager.CreateLobbyViaHTTP(actualUserID, req.PlayerName, req.LobbyName, req.PlayerAvatar, req.IsPrivate)
	if err != nil {
		log.Error("Failed to create lobby", "error", err, "player_name", req.PlayerName)
		http.Error(w, fmt.Sprintf("Failed to create lobby: %v", err), http.StatusInternalServerError)
		return
	}

	// Record metrics
	metrics.RecordLobbyCreated()

	// Add user to active session tracker
	if err := s.activeUserTracker.AddUserSession(actualUserID, lobbyID, hostPlayerID); err != nil {
		log.Error("Failed to add user to active session tracker", "error", err, "user_id", actualUserID)
		// Don't fail the request, just log the error
	}

	response := CreateLobbyResponse{
		GameID:       lobbyID,
		PlayerID:     hostPlayerID,
		SessionToken: sessionToken,
	}

	log.Info("Lobby created successfully", "lobby_id", lobbyID, "host_player_id", hostPlayerID, "user_id", actualUserID)

	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(http.StatusCreated)
	json.NewEncoder(w).Encode(response)
}

